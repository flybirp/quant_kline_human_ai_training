//
// 来源：/Users/flybirp/Documents/quant_discover —— 补齐《持有》《卖》两块：
//   d24 持有期与止损全景（五强信号的 ΔE / 甜点 / 止损否决）
//   d25 退出规则回测（trail 是唯一有效主动退出；时间止损六信号全败）
//   d26 卖出谱系（浮盈 IC -0.44 / 回撤 IC +0.49；RPS 衰减无效）
//   d27 MA20 破位卖飞率 70%、期望磨掉 87%
//   d29 金叉退出参数曲面（激活 30 段是平原；死叉倒数第二；OR 叠加是负改进）
//
// ⚠️ 与买入侧形态共用同一套市场认知（patterns.ts），但结论方向是「卖的手段极其贫瘠」：
//    大量看似合理的卖出方式已被统计证伪，先证伪清单、再给唯一有效手段。
//
// 注入策略：仅在持仓时注入（控制 token 成本，空仓时不需要卖出指引）。

export interface ExitGuideInput {
  floatPnlRate: number; // 浮动盈亏率（0.05 = +5%，-0.08 = -8%）
}

// 已被统计证伪的退出做法（原文数字，勿删——AI 极易自发发明这些做法）
const REFUTED_EXITS = [
  '固定百分比止损：-5%~-15% 是噪音区，各档 ΔE 全负（腰斩信号 -15% 档仍 -19pct），-5% 档触发率 66~89%，被止损的赢家后续平均还赚 +13~30%',
  '时间止损（N 天不涨就出）：六信号全败，且坑位之后往往正是甜点期',
  '均线破位退出（MA20/MA60 跌破卖出）：卖飞率 70%、卖对率仅 8%、20 日内再入场 78%，期望磨掉 87%——范式性失效，与参数无关',
  '跌破支撑/前低就卖：失败判定信号 ≠ 退出规则（spring 跌破支撑卖出把 E 从 8.91 砍到 4.83）',
  'K 线形态逃顶：形态类特征 AUC 全部 ≈0.5 且年度方向翻转，事前不可识别',
];

export function exitGuideBlock(input: ExitGuideInput): string[] | null {
  const lines: string[] = [];
  lines.push('【持有与卖出】（quant_discover d24~d29，12 年全市场统计；仅在持仓时给出）');

  // 当前状态语义：浮盈是反向信号、回撤是正向信号（d26）
  const pnl = input.floatPnlRate;
  const pnlPct = (pnl * 100).toFixed(1);
  if (pnl > 0.2) {
    lines.push(
      `当前浮盈 +${pnlPct}%：浮盈是最强的**反向**状态（IC -0.44，其中约 3/4 是大盘 beta，剔除后 -0.125）；大幅浮盈时应考虑移动止盈而非继续加仓`,
    );
  } else if (pnl > 0) {
    lines.push(`当前浮盈 +${pnlPct}%：浮盈为弱反向信号（IC -0.44），可用 trail 锁定，勿因浮盈而加仓`);
  } else if (pnl > -0.15) {
    lines.push(
      `当前浮亏 ${pnlPct}%：**回撤越深越该拿**（回撤 IC +0.49，12/12 年为正；回撤深组后续 E60 +41.9% vs 浅组 -2.4%），此区间属噪音区，止损是逆向操作`,
    );
  } else {
    lines.push(
      `当前浮亏 ${pnlPct}%：已超出噪音区（-5%~-15%），若当初是深档信号，统计上仍建议持有（回撤 IC +0.49）；若要安全网，只可设深档灾难保险（-30%~-45%），不要用 -5%~-15%`,
    );
  }

  lines.push('');
  lines.push('已被统计证伪的退出做法——**不要使用**：');
  for (const r of REFUTED_EXITS) lines.push(`- ${r}`);

  lines.push('');
  lines.push('唯一有效的主动退出：**移动止盈 trail**（浮盈达 X% 后自最高点回落 Y% 卖出），参考档位：腰斩类 trail(30/10)、底背离 trail(20/8)、spring trail(20/10)、绝望组 trail(20/8)；或干脆持有到期。');
  lines.push('持有期甜点：腰斩/绝望组 90 日（**40 日是坑，勿在此离场**）；筑底跌破、底背离 越长越好（180 日仍未吃完，禁止止盈）；spring U 型（20 日可用 → 60 日难受 → 180 日再起）。');
  lines.push('风险控制请落在**仓位规模**（单票上限），不要靠价格止损位；退出规则不要叠加（OR 组合是负改进）。');

  return lines;
}
